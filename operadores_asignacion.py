#----OPERADORES DE ASIGNACION----

#Asignación =
x=5
print(x)

#Asignación con suma +=
x = x + 2
print(x)
x+=2#aca se simplifica y  ya x no vale 5 si no que vale 7

#Asignacion con resta -*
x = -3
x -=3
print(x)

#Asignación con multiplicación
x = x*4
x *=4
print(x)

#Asignacion con division /=
x = x/2
x/=2
print(x)

#Asignacion con division entera  //=
x=x//2
x//=2
print(x)

#Asignacion con mudulo
x=x%2
x%=2
print(x)

#Asignacion con exponenciacion 
x=x**2
x**=2
print(x)

